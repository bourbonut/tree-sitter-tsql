
const {
  ANSI_DEFAULTS,
  ANSI_NULLS,
  ANSI_NULL_DFLT_OFF,
  ANSI_NULL_DFLT_ON,
  ANSI_PADDING,
  ANSI_WARNINGS,
  ARITHABORT,
  ARITHIGNORE,
  COMMITTED,
  CONCAT_NULL_YIELDS_NULL,
  CURSOR_CLOSE_ON_COMMIT,
  DECIMA,
  DECIMAL,
  FMTONLY,
  FORCEPLAN,
  IDENTITY_INSERT,
  IMPLICIT_TRANSACTIONS,
  IO,
  ISOLATION,
  LEVEL,
  LOCAL_ID,
  NOCOUNT,
  NOEXEC,
  NUMERIC_ROUNDABORT,
  PARSEONLY,
  PROFILE,
  QUOTED_IDENTIFIER,
  READ,
  REMOTE_PROC_TRANSACTIONS,
  REPEATABLE,
  ROWCOUNT,
  SERIALIZABLE,
  SET,
  SHOWPLAN_ALL,
  SHOWPLAN_TEXT,
  SHOWPLAN_XML,
  SNAPSHOT,
  STATISTICS,
  TEXTSIZE,
  TIME,
  TRANSACTION,
  UNCOMMITTED,
  XACT_ABOR,
  XML,
} = require("./lexer.js");

module.exports = {
  // https://msdn.microsoft.com/en-us/library/ms190356.aspx
  // Runtime check.
  set_special: $ => choice(
    seq(SET, $.id_, choice(seq($.id_, constant_LOCAL_ID, $.on_off),), optional(';')),
    seq(SET, STATISTICS, choice(seq(IO, TIME, XML, PROFILE),), $.on_off, optional(';')),
    seq(SET, ROWCOUNT, choice(seq(LOCAL_ID, DECIMAL),), optional(';')),
    seq(SET, TEXTSIZE, DECIMAL, optional(';')),
    // https://msdn.microsoft.com/en-us/library/ms173763.aspx
    seq(SET, TRANSACTION, ISOLATION, LEVEL, choice(
      seq(READ, UNCOMMITTED),
      seq(READ, COMMITTED),
      seq(REPEATABLE, READ),
      SNAPSHOT,
      SERIALIZABLE,
      DECIMA
    ), optional(';')),
    // https://msdn.microsoft.com/en-us/library/ms188059.aspx
    seq(SET, IDENTITY_INSERT, $.table_name, $.on_off, optional(';')),
    seq(SET, $.special_list, repeat(seq(',', $.special_list),), $.on_off),
    seq(SET, $.modify_method),
  ),

  special_list: _ => choice(
    ANSI_NULLS,
    QUOTED_IDENTIFIER,
    ANSI_PADDING,
    ANSI_WARNINGS,
    ANSI_DEFAULTS,
    ANSI_NULL_DFLT_OFF,
    ANSI_NULL_DFLT_ON,
    ARITHABORT,
    ARITHIGNORE,
    CONCAT_NULL_YIELDS_NULL,
    CURSOR_CLOSE_ON_COMMIT,
    FMTONLY,
    FORCEPLAN,
    IMPLICIT_TRANSACTIONS,
    NOCOUNT,
    NOEXEC,
    NUMERIC_ROUNDABORT,
    PARSEONLY,
    REMOTE_PROC_TRANSACTIONS,
    SHOWPLAN_ALL,
    SHOWPLAN_TEXT,
    SHOWPLAN_XML,
    XACT_ABOR,
  ),

  constant_LOCAL_ID: $ => choice($.constant, LOCAL_ID),
}
